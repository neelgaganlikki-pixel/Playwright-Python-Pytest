import xml.etree.ElementTree as ET
import pandas as pd
from pathlib import Path

def parse_junit_xml(xml_path: str):
    """Reads the pytest JUnit XML report and extracts test execution metrics."""
    if not Path(xml_path).exists():
        print(f"Error: {xml_path} not found.")
        return None
        
    tree = ET.parse(xml_path)
    root = tree.getroot()
    
    records = []
    # Loop through every test case in the XML report
    for testcase in root.iter('testcase'):
        name = testcase.get('name')
        classname = testcase.get('classname', 'unknown')
        time = float(testcase.get('time', 0.0))
        
        # Check if the test failed or had an error
        failure = testcase.find('failure')
        error = testcase.find('error')
        status = 1 if (failure is not None or error is not None) else 0 # 1 = Fail, 0 = Pass
        
        records.append({
            'test_name': name,
            'module': classname.split('.')[0],
            'execution_duration_sec': time,
            'test_failed': status
        })
        
    df = pd.DataFrame(records)
    return df

if __name__ == "__main__":
    # Point to the XML generated by your Jenkins run
    xml_file = "test-results/pytest-results.xml"
    
    print("Parsing test results...")
    df = parse_junit_xml(xml_file)
    
    if df is not None and not df.empty:
        print("\nSuccessfully extracted test data:")
        print(df.head())
        
        # Save it into a CSV file so our AI model can read it later
        Path("ml").mkdir(exist_ok=True)
        df.to_csv("ml/historical_test_data.csv", index=False)
        print("\nSaved extracted data to ml/historical_test_data.csv")
    else:
        print("No test records found to parse.")